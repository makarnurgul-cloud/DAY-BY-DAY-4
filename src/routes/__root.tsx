function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="kk">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  useEffect(() => {
    const navigateHome = () => { if (window.location.pathname === '/' || window.location.pathname === '/auth') router.navigate({to:'/dashboard',replace:true}); };
    supabase.auth.getUser().then(({data}) => {if(data.user) navigateHome();});
    const {data} = supabase.auth.onAuthStateChange((event) => {
      if (event !== 'SIGNED_IN' && event !== 'SIGNED_OUT' && event !== 'USER_UPDATED') return;
      router.invalidate();
      if (event !== 'SIGNED_OUT') {queryClient.invalidateQueries(); if(event==='SIGNED_IN') navigateHome();}
    });
    return () => data.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster />
    </QueryClientProvider>
  );
}
